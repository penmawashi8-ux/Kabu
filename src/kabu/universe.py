# 画面のプルダウンと同じ、ごく主要な銘柄だけ。手早く試したいとき用。
MAJOR_CODES = (
    "7203", "6758", "9984", "6861", "8306", "9432", "9433", "6098",
    "8035", "7974", "6501", "8058", "7267", "4063", "4568", "6902",
)

UNIVERSES = ("major", "large")


def _to_symbol(code: str) -> str:
    """「7203」「7203.T」「7203 トヨタ」のどれでも 7203.T にする。"""
    head = code.strip().split()[0] if code.strip() else ""
    head = head.split(",")[0].strip().upper()
    if not head:
        return ""
    return head if "." in head else f"{head}.T"


def symbols(name: str) -> list[str]:
    """名前で指定された一覧を銘柄コードに変換する。"""
    if name == "major":
        return [_to_symbol(c) for c in MAJOR_CODES]
    if name == "large":
        return [_to_symbol(c) for c in LARGE]
    raise ValueError(f"知らない銘柄リストです: {name}（使えるのは {', '.join(UNIVERSES)}）")


def from_file(path: str | Path) -> list[str]:
    """ファイルから銘柄を読む。1 行 1 銘柄。

    `7203` / `7203.T` / `7203,トヨタ自動車` / `7203 トヨタ自動車` のどれでもよい。
    空行と # で始まる行は読み飛ばす（コピペした一覧をそのまま使えるように）。
    """
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    out: list[str] = []
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        symbol = _to_symbol(stripped)
        if symbol and symbol not in out:
            out.append(symbol)
    return out


def name_of(symbol: str) -> str:
    """銘柄コードから会社名。分からなければ空文字。"""
    return LARGE.get(symbol.split(".")[0], "")
